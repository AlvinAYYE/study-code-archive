bool isNumber(char* s) {
    int n, m;
    
    // skip leading spaces
    while (*s == ' ') s ++;
    
    n = m = 0;
    
    // skip the sign of the number
    if (*s == '+' || *s == '-') s ++;
    
    while (*s >= '0' && *s <= '9') {
        n ++;
        s ++;
    }
    
    if (*s == '.') {
        s ++;
        while (*s >= '0' && *s <= '9') {
            m ++;
            s ++;
        }
        if (!n && !m) return false;
    } else if (!n) {
        return false;
    }
    
    if (*s == 'e' || *s == 'E') {
        s ++;
        if (*s == '+' || *s == '-') s ++;
        n = 0;
        while (*s >= '0' && *s <= '9') {
            n ++;
            s ++;
        }
        if (!n) return false;
    }
    
    while (*s == ' ') s ++;
    
    return *s == 0 ? true : false;
}


