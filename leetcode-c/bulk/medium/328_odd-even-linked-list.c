/**

328. Odd Even Linked List [Medium]

Given a singly linked list, group all odd nodes together followed by the even nodes. Please note here we are talking about the node number and not the value in the nodes.

You should try to do it in place. The program should run in O(1) space complexity and O(nodes) time complexity.

Example 1:
Input: 1->2->3->4->5->NULL
Output: 1->3->5->2->4->NULL

Example 2:
Input: 2->1->3->5->6->4->7->NULL
Output: 2->3->6->7->1->5->4->NULL

Note:
The relative order inside both the even and odd groups should remain as it was in the input.
The first node is considered odd, the second node even and so on ...
  
 */

/**
 * Definition for singly-linked list.
 * 
 */
struct ListNode* oddEvenList(struct ListNode* head){
    struct ListNode *oddHead = head;
    struct ListNode *OddTailNode = head;
    struct ListNode *evenHead = NULL;
    struct ListNode *evenTmp = NULL;

    if (oddHead == NULL)
    {
        return NULL;
    }
    if (oddHead->next != NULL)
    {
        evenHead = evenTmp = oddHead->next;
    }

    while (oddHead != NULL && evenHead != NULL)
    {
        struct ListNode *tmpHead = NULL;
        OddTailNode = oddHead;
        /* save the next round odd pointer */
        if (evenHead->next)
        {
            tmpHead = oddHead->next->next;
        }

        /* case1: [odd]->[even]->[...] */
        if (evenHead->next)
        {
            evenHead->next = evenHead->next->next;
            oddHead->next = tmpHead;

            /* jump to next twice */
            oddHead = oddHead->next;
            evenHead = evenHead->next;
        }
        /* case2: [odd]->[even]->NULL, even->next is NULL */
        else
        {
            oddHead->next = NULL;
            break;
        }
    }

    if (oddHead == NULL)
    {
        OddTailNode->next = evenTmp;
    } else
    {
        oddHead->next = evenTmp;
    }

    return head;
}

