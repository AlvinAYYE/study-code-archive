int hIndex(int* citations, int citationsSize) {
    int i, h = 0;
    for (i = 0; i < citationsSize; i ++) {
        if (citations[citationsSize - 1 - i] >= i + 1) {
            h = i + 1;
        } else {
            break;
        }
    }
    return h;
}


