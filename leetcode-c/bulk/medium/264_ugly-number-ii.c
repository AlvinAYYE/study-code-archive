int nthUglyNumber(int n) {
    int i, u2, u3, u5, k2, k3, k5, k;
    int *p, sz;
    
    p  = malloc(n * sizeof(int));
    //assert(p);
    
    p[0] = 1;
    u2 = u3 = u5 = 0;
    
    for (i = 1; i < n; i ++) {  // more like dp solution, 3ms
        k2 = p[u2] * 2;
        k3 = p[u3] * 3;
        k5 = p[u5] * 5;
        k = k2 < k3 ? k2 : k3;
        k = k  < k5 ? k  : k5;
        if (k == k2) u2 ++;
        if (k == k3) u3 ++;
        if (k == k5) u5 ++;
        p[i] = k;
    }
    
    k = p[n - 1];
    free(p);
    
    return k;
}


