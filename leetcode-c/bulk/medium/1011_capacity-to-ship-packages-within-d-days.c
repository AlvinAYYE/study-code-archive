int count_days(int *weight, int sz, int k) {
    int i, w = 0, d = 1;
    for (i = 0; i < sz; i ++) {
        if (w + weight[i] > k) {
            d ++;
            w = 0;
        }
        w += weight[i];
    }
    return d;
}
 
int shipWithinDays(int* weights, int weightsSize, int D){
    int left, right, mid;
    int i, w, d;
    
    left = right = 0;
    
    for (i = 0; i < weightsSize; i ++) {
        w = weights[i];
        if (left < w) left = w;
        right += w;
    }

    while (left < right) {
        mid = left + (right - left) / 2;
        d = count_days(weights, weightsSize, mid);
        if (d <= D) {
            right = mid;
        } else {
            left = mid + 1;
        }
    }
    
    return left;
}


