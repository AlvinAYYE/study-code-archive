bool isAnagram(char* s, char* t) {
    int n1[26] = { 0 }, n2[26] = { 0 };
    int i, j;
    
    while (*s && *t) {
        i = *s - 'a';
        j = *t - 'a';
        n1[i] ++;
        n2[j] ++;
        s ++;
        t ++;
    }
    
    if (*s || *t) return false;
    
    for (i = 0; i < 26; i ++) {
        if (n1[i] != n2[i]) return false;
    }
    
    return true;
}


