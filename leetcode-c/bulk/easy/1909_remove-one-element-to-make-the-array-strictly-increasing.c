bool canBeIncreasing(int* nums, int numsSize) {
    int i, used = 0, prev = 0;
    for (i = 0; i < numsSize; ++i) {
        if (i && nums[i] <= prev) {
            if (used) return false;
            used = 1;
            if (i >= 2 && nums[i] <= nums[i - 2]) prev = nums[i - 1];
            else prev = nums[i];
        } else prev = nums[i];
    }
    return true;
}

