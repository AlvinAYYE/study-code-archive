int* relativeSortArray(int* arr1, int arr1Size, int* arr2, int arr2Size,
                       int* returnSize) {
    int count[1001] = {0};
    for (int i = 0; i < arr1Size; ++i) {
        ++count[arr1[i]];
    }

    int* answer = (int*)malloc((size_t)arr1Size * sizeof(int));
    int out = 0;

    // 先依照 arr2 指定的優先順序輸出。
    for (int i = 0; i < arr2Size; ++i) {
        int value = arr2[i];
        while (count[value] > 0) {
            answer[out++] = value;
            --count[value];
        }
    }

    // 剩下的數值依照計數表索引遞增輸出。
    for (int value = 0; value <= 1000; ++value) {
        while (count[value] > 0) {
            answer[out++] = value;
            --count[value];
        }
    }

    *returnSize = out;
    return answer;
}

