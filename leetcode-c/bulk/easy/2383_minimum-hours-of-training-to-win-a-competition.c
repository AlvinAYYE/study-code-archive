int minNumberOfHours(int initialEnergy, int initialExperience, int* energy, int energySize, int* experience, int experienceSize) {
    int i, hours = 0, e = initialEnergy, x = initialExperience;
    for (i = 0; i < energySize; ++i) {
        if (e <= energy[i]) { hours += energy[i] - e + 1; e = energy[i] + 1; }
        e -= energy[i];
    }
    for (i = 0; i < experienceSize; ++i) {
        if (x <= experience[i]) { hours += experience[i] - x + 1; x = experience[i] + 1; }
        x += experience[i];
    }
    return hours;
}

