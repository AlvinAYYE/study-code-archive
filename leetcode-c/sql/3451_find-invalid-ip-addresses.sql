-- 3451. 找出無效 IP 位址（Find Invalid IP Addresses）
-- 題目完整翻譯：logs 記錄伺服器存取資訊。找出所有無效的 IPv4 字串，按 ip 分組計算出現次數 invalid_count；若有任一段大於 255、有前導零，或不是恰好四段，就屬於無效。結果先依 invalid_count 降冪，再依 ip 降冪排列。
-- 資料表與鍵：logs(log_id INT, ip VARCHAR, status_code INT)；log_id 為唯一鍵。status_code 不影響判斷。
-- 範例輸入重點：192.168.1.1 出現兩次（有效）；256.1.2.3 出現兩次（某段大於 255）；192.168.001.1 出現兩次（有前導零）；192.168.1 出現一次（只有三段）。
-- 範例輸出：256.1.2.3 | 2；192.168.001.1 | 2；192.168.1 | 1。
-- 限制：題目指出每個八位組含 1 到 3 位數；沒有額外列出資料列數限制。
-- 解題步驟：用 IPv4 八位組的有效格式組成完整正規表示式。每段只允許 0 到 255，且 0 只能單獨出現、非零數字不可有前導零；四段間必須剛好有三個點。取不符合完整格式的列，再按 IP 彙總。
-- 複雜度：對 N 筆紀錄逐筆比對，約 O(N × L)；分組及排序最多 O(N log N)，L 為 IP 字串長度。

SELECT
    ip,
    COUNT(*) AS invalid_count
FROM logs
WHERE NOT REGEXP_LIKE(
    ip,
    '^(25[0-5]|2[0-4][0-9]|1[0-9]{2}|[1-9][0-9]?|0)[.](25[0-5]|2[0-4][0-9]|1[0-9]{2}|[1-9][0-9]?|0)[.](25[0-5]|2[0-4][0-9]|1[0-9]{2}|[1-9][0-9]?|0)[.](25[0-5]|2[0-4][0-9]|1[0-9]{2}|[1-9][0-9]?|0)$',
    'c'
)
GROUP BY ip
ORDER BY invalid_count DESC, ip DESC;
