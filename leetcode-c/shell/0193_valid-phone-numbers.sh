#!/bin/sh
# LeetCode 193. Valid Phone Numbers（有效電話號碼）
# 題目翻譯：file.txt 每行有一個電話號碼。只輸出符合下列任一格式的整行：
# (xxx) xxx-xxxx 或 xxx-xxx-xxxx；x 必須是數字。
#
# 輸入範例（file.txt）：
# 987-123-4567
# 123 456 7890
# (123) 456-7890
# 輸出範例：
# 987-123-4567
# (123) 456-7890
#
# 限制：每行不含前置或尾端空白；只需辨認上述兩種格式。
# 解題步驟：grep -E 啟用擴充正規表示式；^ 和 $ 要求整行完全符合；| 表示兩種格式擇一。
# [0-9]{3} 與 [0-9]{4} 分別要求三位與四位數字；\(、\) 用來比對實際括號。
# 複雜度：令 N 為檔案字元數，時間 O(N)；grep 逐行讀取，額外空間 O(1)。
# 題目：https://leetcode.com/problems/valid-phone-numbers/

grep -E '^([0-9]{3}-[0-9]{3}-[0-9]{4}|\([0-9]{3}\) [0-9]{3}-[0-9]{4})$' file.txt
